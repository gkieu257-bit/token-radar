// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// pre-token protocol below the floor that the house's own watchlist rule would keep: no token on
// record, and no wrapped, staked or bridged product of a token that already trades. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board. They do a second job: they calibrate the model (see below).
//
// Implied value follows only from the snapshot's own figures:
//
//   category multiple = the median market-cap-per-TVL of the live-token protocols in the same
//                         category, shrunk toward the overall median with a prior of 15 protocols
//                         (a category with few live tokens leans on the whole market), then
//                         clamped to [0.05, 1.00]. A category with no live token uses the overall
//                         median, 0.169 on this snapshot. This is how a token is really valued:
//                         against the multiples its own kind of protocol already trades at.
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   maturity   = 0.7 + min(age_days, 730) / 730 x 0.3   (age_days unknown: 365)
//   chains     = 1 + 0.02 x min(chains - 1, 5)
//   implied    = max(1, round(tvl_usd x categoryMultiple x growthMult x maturityMult x chains))
//
// The constants are stated in the dashboard and changeable in the model sandbox. No protocol name
// is ever special-cased: the same function scores every row, and the category multiples are computed
// from the snapshot at run time, never written in by hand.

