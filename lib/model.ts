const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The median of a sorted list of numbers; null when the list is empty. */
function median(sorted: number[]): number | null {
  if (sorted.length === 0) return null;
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/**
 * The category calibration, computed from the snapshot's own live-token protocols: for every
 * category the median market-cap-per-TVL of the protocols in it that already trade, shrunk toward
 * the overall median with a prior of `model.category_prior` protocols, then clamped. A category
 * with no live token at all takes the overall median. The table is returned sorted by category so
 * the dashboard and the dossier read it the same way every run.
 */
export function calibrate(snapshot: Snapshot, model: ModelConstants = MODEL): { overall: number; table: CalibrationRow[] } {
  const ratios = new Map<string, number[]>();
  const all: number[] = [];
  for (const p of snapshot.protocols) {
    if (p.mcap_usd === null || p.tvl_usd <= 0) continue;
    const r = p.mcap_usd / p.tvl_usd;
    if (!Number.isFinite(r) || r < 0) continue;
    all.push(r);
    const key = p.category ?? 'Other';
    const list = ratios.get(key) ?? [];
    list.push(r);
    ratios.set(key, list);
  }
  all.sort((a, b) => a - b);
  const overall = median(all) ?? 0.17;
  const table: CalibrationRow[] = [];
  const cats = new Set<string>();
  for (const p of snapshot.protocols) cats.add(p.category ?? 'Other');
  for (const cat of [...cats].sort()) {
    const list = (ratios.get(cat) ?? []).sort((a, b) => a - b);
    const med = median(list);
    const n = list.length;
    const raw = med === null ? overall : (n * med + model.category_prior * overall) / (n + model.category_prior);
    const multiple = Math.min(model.category_cap, Math.max(model.category_floor, raw));
    table.push({ category: cat, live_n: n, median_ratio: med === null ? null : Math.round(med * 1000) / 1000, multiple: Math.round(multiple * 1000) / 1000 });
  }
  return { overall: Math.round(overall * 1000) / 1000, table };
}

/** The category multiple for one protocol, from the calibration table. */
function multipleFor(table: CalibrationRow[], category: string | null, overall: number): number {
  const row = table.find((r) => r.category === (category ?? 'Other'));
  return row === undefined ? overall : row.multiple;
}

/** The three multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  model: ModelConstants,
  table: CalibrationRow[],
  overall: number,
): { implied: number; catMult: number; growthPct: number; growthMult: number; maturityMult: number; chainMult: number; age: number | null } {
  const age = ageDays(asOf, protocol.listed_at);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult = model.maturity_floor + (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const chainCount = Math.max(1, protocol.chains.length);
  const chainMult = 1 + model.chain_step * Math.min(chainCount - 1, model.chain_max_extra);
  const catMult = multipleFor(table, protocol.category, overall);
  const base = protocol.tvl_usd * catMult;
  const implied = Math.max(1, Math.round(base * growthMult * maturityMult * chainMult));
  return { implied, catMult, growthPct, growthMult, maturityMult, chainMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;
/** A whole word wrapped, staked or staking in a name: a product of a token that already trades. */
const WRAPPED = /\b(wrapped|staked|staking)\b/i;
/** An exchange's name at the start of a protocol's name. */
const EXCHANGES = ['Binance', 'Coinbase', 'Bybit', 'Kraken', 'Bitget', 'OKX', 'Bitfinex', 'Gemini'];
/** Categories that are a wrapped, staked or bridged product of a token that already trades. */
const EXCLUDED_CATEGORIES = new Set(['Bridge', 'Canonical Bridge', 'Liquid Staking', 'Liquid Restaking', 'Restaked BTC', 'CEX']);

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/**
 * Whether a protocol is one the board may rank: pre-token, and not a wrapped, staked or bridged
 * product of a token that already trades — the house watchlist rule, applied to the early radar
 * too, so the board never ranks a CEX, a bridge or a staking wrapper as a token still to come.
 */
export function isRankable(p: SnapshotProtocol): boolean {
  if (!isPreToken(p)) return false;
  if (p.category !== null && EXCLUDED_CATEGORIES.has(p.category)) return false;
  if (VERSIONED.test(p.name)) return false;
  if (WRAPPED.test(p.name)) return false;
  if (EXCHANGES.some((e) => p.name.startsWith(e))) return false;
  return true;
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** The headline sentence's figures: how many watchlist slugs, how many rows, how many live protocols. */
